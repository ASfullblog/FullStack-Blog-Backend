const indexes = [
  'CREATE INDEX IF NOT EXISTS idx_posts_created_at ON posts (created_at)',
  'CREATE INDEX IF NOT EXISTS idx_comments_post_id ON comments (post_id)',
  'CREATE INDEX IF NOT EXISTS idx_notifications_user_id ON notifications (user_id)',
  'CREATE INDEX IF NOT EXISTS idx_game_levels_game_id ON game_levels (game_id)',
  'CREATE INDEX IF NOT EXISTS idx_game_stage_configs_active ON game_stage_configs (game_slug, is_active)',
  'CREATE INDEX IF NOT EXISTS idx_sensitive_word_logs_source ON sensitive_word_logs (source_type, source_id)'
];

const jsonColumns = new Set([
  'tech_stack',
  'visited_provinces',
  'games_data',
  'tags',
  'board_data',
  'evacuation_config',
  'config_data',
  'matched_words'
]);

const tableOrder = [
  'users',
  'categories',
  'tags',
  'posts',
  'comments',
  'post_tags',
  'sys_config',
  'games',
  'game_levels',
  'game_favorites',
  'game_ratings',
  'game_tag_rel',
  'game_category_rel',
  'user_level_records',
  'notifications',
  'game_stage_configs',
  'sensitive_words',
  'sensitive_word_whitelist',
  'sensitive_word_logs'
];

const identityTables = tableOrder.filter((table) => ![
  'sys_config',
  'post_tags',
  'game_tag_rel',
  'game_category_rel'
].includes(table));

const quoteIdentifier = (value) => `"${value.replace(/"/g, '""')}"`;
const quoteMysqlIdentifier = (value) => `\`${value.replace(/`/g, '``')}\``;

const normalizeValue = (column, value) => {
  if (value === undefined) return null;
  if (jsonColumns.has(column) && value !== null && typeof value !== 'string') {
    return JSON.stringify(value);
  }
  return value;
};

const migrateTable = async (mysqlConnection, table) => {
  const [rows] = await mysqlConnection.query(`SELECT * FROM ${quoteMysqlIdentifier(table)}`);
  if (rows.length === 0) {
    console.log(`${table}: 0 rows`);
    return;
  }

  const columns = Object.keys(rows[0]);
  const columnSql = columns.map(quoteIdentifier).join(', ');
  const placeholders = columns.map((_, index) => `$${index + 1}`).join(', ');
  const conflict = table === 'post_tags' || table === 'game_tag_rel' || table === 'game_category_rel'
    ? ' ON CONFLICT DO NOTHING'
    : table === 'sys_config'
      ? ' ON CONFLICT (config_key) DO UPDATE SET config_value = EXCLUDED.config_value, config_description = EXCLUDED.config_description'
      : table === 'users' || table === 'categories' || table === 'tags' || table === 'posts' || table === 'games'
        ? ` ON CONFLICT (id) DO UPDATE SET ${columns.filter((column) => column !== 'id').map((column) => `${quoteIdentifier(column)} = EXCLUDED.${quoteIdentifier(column)}`).join(', ')}`
        : ' ON CONFLICT DO NOTHING';
  const statement = `INSERT INTO ${quoteIdentifier(table)} (${columnSql}) VALUES (${placeholders})${conflict}`;

  for (const row of rows) {
    await sql.query(statement, columns.map((column) => normalizeValue(column, row[column])));
  }
  console.log(`${table}: ${rows.length} rows`);
};

const syncSequence = async (table) => {
  const sequence = await sql.query(
    `SELECT pg_get_serial_sequence($1, 'id') AS sequence`,
    [table]
  );
  const sequenceName = sequence.rows[0]?.sequence;
  if (!sequenceName) return;
  await sql.query(
    `SELECT setval($1, COALESCE((SELECT MAX(id) FROM ${quoteIdentifier(table)}), 1), true)`,
    [sequenceName]
  );
};

async function main() {
  const mysqlConnection = await mysql.createConnection(local);
  try {
    for (const statement of schema) {
      await sql.query(statement);
    }
    for (const statement of indexes) {
      await sql.query(statement);
    }

    for (const table of tableOrder) {
      await migrateTable(mysqlConnection, table);
    }

    for (const table of identityTables) {
      await syncSequence(table);
    }

    const checks = await Promise.all(['users', 'posts', 'games', 'game_levels', 'comments'].map(async (table) => {
      const result = await sql.query(`SELECT COUNT(*)::int AS count FROM ${quoteIdentifier(table)}`);
      return `${table}=${result.rows[0].count}`;
    }));
    console.log(`Neon migration complete: ${checks.join(', ')}`);
  } finally {
    await mysqlConnection.end();
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
