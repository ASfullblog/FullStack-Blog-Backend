/**
 * 访问采集中间件（fire-and-forget，绝不阻塞响应）
 *
 * 关键约束（Neon 是 HTTP 驱动：一次 query 一次往返，无事务无连接池）：
 * - 采集动作挂在 res.on('finish') 上，也就是**响应已经发出去之后**才开始解析 IP / 写库，
 *   所以外部接口再慢也不会拖慢用户请求。
 * - 全程 try/catch 吞掉错误，写库失败只打一条 warn（不打印明文 IP）。
 * - 只采集「页面数据接口」，跳过鉴权、上传、统计自身、静态资源与非 2xx/3xx。
 *
 * Lead 需要做的注册（本文件不自行挂载）：
 *   import visitTracker from './middleware/visitTracker';
 *   app.use(visitTracker);   // 位置见汇报：在请求日志中间件之后、业务路由注册之前
 */
import { Request, Response, NextFunction } from 'express';
import { createHash } from 'crypto';
import pool from '../config/database';
import { getClientIp, isLocalOrPrivateIp, maskIp, resolveIpLocation } from '../services/ipLocation';

/** 幂等建表 SQL：脚本与应用启动都可安全执行（Neon HTTP 无事务，故逐条执行） */
export const VISIT_LOGS_DDL: string[] = [
  `CREATE TABLE IF NOT EXISTS visit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ip VARCHAR(64),
    ip_hash CHAR(64),
    province VARCHAR(32),
    city VARCHAR(64),
    country VARCHAR(64),
    path VARCHAR(255),
    user_agent VARCHAR(512),
    referrer VARCHAR(512),
    user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`,
  `CREATE INDEX IF NOT EXISTS idx_visit_logs_created_at ON visit_logs (created_at)`,
  `CREATE INDEX IF NOT EXISTS idx_visit_logs_province ON visit_logs (province)`,
  `CREATE INDEX IF NOT EXISTS idx_visit_logs_province_created ON visit_logs (province, created_at)`,
  `CREATE INDEX IF NOT EXISTS idx_visit_logs_ip_created ON visit_logs (ip_hash, created_at)`,
  `CREATE TABLE IF NOT EXISTS ip_cache (
    ip VARCHAR(64) PRIMARY KEY,
    province VARCHAR(32),
    city VARCHAR(64),
    country VARCHAR(64),
    provider VARCHAR(32),
    hits INTEGER NOT NULL DEFAULT 1,
    resolved_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`,
  `CREATE INDEX IF NOT EXISTS idx_ip_cache_resolved_at ON ip_cache (resolved_at)`
];

/** 应用启动时可选调用：幂等、失败静默（不抛错、不阻塞） */
export const ensureVisitSchema = async (): Promise<void> => {
  for (const ddl of VISIT_LOGS_DDL) {
    try {
      await pool.query(ddl);
    } catch (e: any) {
      console.warn('[visitTracker] 建表跳过:', e?.message || e);
      return;
    }
  }
};

/** 需要计入访问量的业务接口前缀（页面数据接口） */
const TRACKED_PREFIXES = [
  '/api/posts',
  '/api/categories',
  '/api/tags',
  '/api/comments',
  '/api/quotes',
  '/api/games',
  '/api/game-level-configs',
  '/api/parking-rush',
  '/api/archive',
  '/api/users/me'
];

/** 明确排除：登录/注册/验证码等（高频且无统计意义）、上传、统计接口自身（防止自计数） */
const EXCLUDED_PREFIXES = [
  '/api/auth',
  '/api/admin',
  '/api/upload',
  '/api/stats',
  '/api/ai',
  '/api/notifications',
  '/uploads'
];

const slice = (v: string | undefined | null, max: number): string | null => {
  if (!v) return null;
  const s = String(v).trim();
  if (!s) return null;
  return s.length > max ? s.slice(0, max) : s;
};

const hashIp = (ip: string): string => createHash('sha256').update(`${ip}|${process.env.IP_HASH_SALT || 'fullstack-blog'}`).digest('hex');

/** 是否该记这笔访问（只看方法与路径；状态码必须等 finish 后再判，见 visitTracker） */
export const shouldTrack = (req: Request): boolean => {
  try {
    if (req.method !== 'GET') return false; // 只统计内容读取（页面数据接口）
    const path = (req.baseUrl ? req.baseUrl + (req.path || '') : req.path) || req.originalUrl || '';
    if (!path.startsWith('/api')) return false;
    if (EXCLUDED_PREFIXES.some((p) => path.startsWith(p))) return false;
    return TRACKED_PREFIXES.some((p) => path.startsWith(p));
  } catch {
    return false;
  }
};

/** 真正落库（独立导出，便于脚本/测试直接调用） */
export const recordVisit = async (info: {
  ip: string;
  path: string;
  userAgent?: string | null;
  referrer?: string | null;
  userId?: number | null;
}): Promise<void> => {
  const { province, city, country } = await resolveIpLocation(info.ip);
  await pool.query(
    `INSERT INTO visit_logs (ip, ip_hash, province, city, country, path, user_agent, referrer, user_id, created_at)
     VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, NOW())`,
    [
      info.ip || null,
      info.ip ? hashIp(info.ip) : null,
      province || '未知',
      slice(city, 64),
      slice(country, 64),
      slice(info.path, 255),
      slice(info.userAgent, 512),
      slice(info.referrer, 512),
      info.userId ?? null
    ]
  );
};

/** 组装并异步写入，绝不 await 到调用方 */
const trackAfterResponse = (req: Request, res: Response) => {
  void (async () => {
    try {
      const ip = getClientIp(req);
      const path = (req.originalUrl || req.url || '').split('?')[0];
      await recordVisit({
        ip,
        path,
        userAgent: String(req.headers['user-agent'] || '') || null,
        referrer: String(req.headers['referer'] || req.headers['referrer'] || '') || null,
        // 兼容两种写法：全局声明没被 ts-node 加载时也不报错
        userId: Number((req as any)?.user?.id ?? (req as any)?.userId ?? 0) || null
      });
    } catch (e: any) {
      // 静默：访问采集失败绝不影响业务；日志只输出脱敏 IP
      console.warn('[visitTracker] 采集失败:', e?.message || e, maskIp(getClientIp(req)));
    }
  })();
};

/**
 * 中间件：不阻塞、不 await、不改写响应
 * 状态码必须在 res.on('finish') 里判（注册时 statusCode 还是默认 200）
 */
export const visitTracker = (req: Request, res: Response, next: NextFunction) => {
  try {
    if (shouldTrack(req)) {
      // finish = 响应已发送，此处开始解析与写库对客户端延迟零影响
      res.on('finish', () => {
        if (res.statusCode >= 400) return; // 报错的请求不计入访问
        trackAfterResponse(req, res);
      });
    }
  } catch (e: any) {
    console.warn('[visitTracker] 钩子注册失败:', e?.message || e);
  }
  next();
};

/** 内网 IP 判定导出，方便 Lead 需要时过滤 */
export { isLocalOrPrivateIp };

export default visitTracker;
